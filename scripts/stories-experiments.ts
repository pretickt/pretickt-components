import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

/**
 * The platform's experiments (`admin/experiments/<slug>/`: `README.md` with a `# Title`, `pt-*.ts`, `pt-*.scenarios.json`,
 * `<slug>.css`) read the way the admin bench reads them, and turned into the module of stories the stories app imports.
 */
export interface ExperimentFiles {
  slug: string;
  title: string;
  css: string;
  components: { tag: string; className: string; source: string; scenarios: string }[];
}

const read = (path: string) => (existsSync(path) ? readFileSync(path, 'utf8') : null);

export function readExperiments(root: string): ExperimentFiles[] {
  if (!existsSync(root)) return [];
  return readdirSync(root).filter((d) => !d.startsWith('.') && statSync(join(root, d)).isDirectory()).sort().map((slug) => {
    const dir = join(root, slug);
    const title = /^#\s+(.+)$/m.exec(read(join(dir, 'README.md')) ?? '')?.[1]?.trim() ?? slug;
    const components = readdirSync(dir).filter((f) => /^pt-[a-z0-9-]+\.ts$/.test(f)).sort().flatMap((f) => {
      const tag = f.slice(0, -'.ts'.length);
      const source = readFileSync(join(dir, f), 'utf8');
      const className = /export class (\w+)/.exec(source)?.[1];
      return className ? [{ tag, className, source, scenarios: read(join(dir, `${tag}.scenarios.json`)) ?? '[]' }] : [];
    });
    return { slug, title, css: read(join(dir, `${slug}.css`)) ?? '', components };
  });
}

/** `.stories/experiments.ts`: each experiment's components, imported from their copies, with their bench presets as stories. */
export function experimentsModule(list: ExperimentFiles[]): string {
  const imports: string[] = [];
  const entries: string[] = [];
  for (const e of list) for (const c of e.components) {
    imports.push(`import { ${c.className} } from './experiments/${e.slug}/${c.tag}';`);
    entries.push(`  ...scenarioStories(${c.className}, ${JSON.stringify(`Experiments · ${e.title}`)}, ${c.scenarios.trim() || '[]'}),`);
  }
  return [
    '// Generated by scripts/stories.ts from the platform\'s experiments — do not edit.',
    "import { scenarioStories, type StoryConfiguration } from '../src/stories/story';",
    ...imports,
    '',
    'export const stories: StoryConfiguration[] = [',
    ...entries,
    '];',
    '',
  ].join('\n');
}

/** `.stories/experiments.css`: every experiment's own classes (the bench inlines them in its previews). */
export const experimentsCss = (list: ExperimentFiles[]): string =>
  list.filter((e) => e.css.trim()).map((e) => `/* ${e.slug} */\n${e.css.trim()}\n`).join('\n');
